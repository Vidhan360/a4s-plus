@contextlib.asynccontextmanager
async def lifespan(app: FastAPI) -> AsyncIterator[None]:
    configure_logging()
    logger.info(
        "starting %s %s (%s)",
        settings.app_name,
        settings.app_version,
        settings.env,
    )
    bus = await init_event_bus()
    logger.info("event bus backend: %s", bus.backend)

    service = get_prediction_service()
    for model in service.describe_all():
        if model["available"]:
            logger.info("ml model ready: %s %s", model["name"], model["version"])
        else:
            logger.warning(
                "ml model unavailable: %s (%s)",
                model["name"],
                model.get("load_error"),
            )
    config_service.invalidate()
    try:
        yield
    finally:
        from app.simulation.engine import simulation_engine

        await simulation_engine.shutdown()
        with contextlib.suppress(Exception):
            await bus.close()
        await engine.dispose()
        logger.info("shutdown complete")


def create_app() -> FastAPI:
    app = FastAPI(
        title=settings.app_name,
        version=settings.app_version,
        description=DESCRIPTION,
        openapi_tags=TAG_METADATA,
        lifespan=lifespan,
        docs_url="/api/docs",
        redoc_url="/api/redoc",
        openapi_url="/api/openapi.json",
    )

    install_rate_limiting(app)

    app.add_middleware(AuditMiddleware)
    app.add_middleware(SecurityHeadersMiddleware)
    app.add_middleware(RequestContextMiddleware)
    app.add_middleware(
        CORSMiddleware,
        allow_origins=settings.cors_origin_list,
        allow_credentials=True,
        allow_methods=["*"],
        allow_headers=["*"],
        expose_headers=["X-Request-ID"],
    )

    # ---------------------------------------------------------- error handlers

    @app.exception_handler(AppError)
    async def handle_app_error(request: Request, exc: AppError) -> JSONResponse:
        return JSONResponse(
            status_code=exc.status_code,
            content=error_body(exc.code, str(exc), exc.details, request_id_ctx.get()),
        )

    @app.exception_handler(RequestValidationError)
    async def handle_validation_error(
        request: Request, exc: RequestValidationError
    ) -> JSONResponse:
        return JSONResponse(
            status_code=HTTP_422,
            content=error_body(
                "validation_error",
                "The request payload failed validation.",
                [
                    {
                        "field": ".".join(str(p) for p in err.get("loc", [])[1:]),
                        "message": err.get("msg", ""),
                        "type": err.get("type", ""),
                    }
                    for err in exc.errors()
                ],
                request_id_ctx.get(),
            ),
        )

    @app.exception_handler(StarletteHTTPException)
    async def handle_http_error(request: Request, exc: StarletteHTTPException) -> JSONResponse:
        return JSONResponse(
            status_code=exc.status_code,
            content=error_body("http_error", str(exc.detail), None, request_id_ctx.get()),
            headers=getattr(exc, "headers", None),
        )

    @app.exception_handler(Exception)
    async def handle_unexpected(request: Request, exc: Exception) -> JSONResponse:
        logger.exception("unhandled error on %s %s", request.method, request.url.path)
        return JSONResponse(
            status_code=500,
            content=error_body(
                "internal_error",
                "An unexpected error occurred. The incident has been logged.",
                None,
                request_id_ctx.get(),
            ),
        )

    app.include_router(api_router)

    @app.get("/", include_in_schema=False)
    async def root() -> dict[str, Any]:
        return {
            "name": settings.app_name,
            "version": settings.app_version,
            "team": "The Third Eye",
            "tagline": "From detection → prediction → prevention",
            "status": "SOFTWARE PROTOTYPE — SIMULATED DATA",
            "docs": "/api/docs",
            "api": "/api/v1",
        }

    @app.get("/docs", include_in_schema=False)
    async def docs_redirect() -> RedirectResponse:
        return RedirectResponse(url="/api/docs", status_code=307)

    @app.get("/redoc", include_in_schema=False)
    async def redoc_redirect() -> RedirectResponse:
        return RedirectResponse(url="/api/redoc", status_code=307)

    return app


app = create_app()
