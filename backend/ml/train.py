"""Reproducible training entry point.

Usage::

    python -m ml.train                      # train LSTM + gradient boosting
    python -m ml.train --model lstm         # LSTM only
    python -m ml.train --epochs 40 --quick  # fast smoke run
    python -m ml.train --help

Produces versioned artifacts under ``ml/artifacts/`` containing the model
weights, the fitted scaler, the feature order, the dataset provenance and the
metrics measured on the held-out test split.

All reported metrics are produced by an actual evaluation run on synthetic,
subject-disjoint held-out data. Nothing is hard-coded.
"""

from __future__ import annotations

import argparse
import json
import random
import sys
import time
from datetime import datetime, timezone
from typing import Any

import numpy as np

from ml.dataset import build_dataset
from ml.evaluate import classification_metrics, format_confusion
from ml.features import FEATURE_NAMES, RISK_CLASSES, StandardScaler
from ml.registry import new_version, save_artifact

DISCLAIMER = (
    "Synthetic training data — research/demo only. Metrics are measured on "
    "held-out synthetic subjects generated by the A4S+ simulation engine. "
    "The model is NOT clinically validated and must not be used for medical "
    "decisions."
)


def set_seed(seed: int) -> None:
    import torch

    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    torch.use_deterministic_algorithms(False)


def class_weights(y: np.ndarray, n_classes: int) -> np.ndarray:
    """Inverse-frequency weights so minority classes are not ignored."""
    counts = np.bincount(y, minlength=n_classes).astype(float)
    counts[counts == 0] = 1.0
    weights = counts.sum() / (n_classes * counts)
    return weights / weights.mean()


def train_lstm(
    bundle: Any,
    scaler: StandardScaler,
    *,
    epochs: int,
    batch_size: int,
    learning_rate: float,
    hidden_size: int,
    num_layers: int,
    dropout: float,
    patience: int,
    seed: int,
    device: str,
) -> tuple[Any, dict[str, Any], dict[str, Any]]:
    import torch
    import torch.nn as nn
    from torch.utils.data import DataLoader, TensorDataset

    from ml.model import AltitudeRiskLSTM, LSTMConfig

    x_train = scaler.transform(bundle.x_train).astype(np.float32)
    x_val = scaler.transform(bundle.x_val).astype(np.float32)
    x_test = scaler.transform(bundle.x_test).astype(np.float32)

    train_ds = TensorDataset(torch.from_numpy(x_train), torch.from_numpy(bundle.y_train))
    generator = torch.Generator().manual_seed(seed)
    train_dl = DataLoader(
        train_ds,
        batch_size=batch_size,
        shuffle=True,
        generator=generator,
        drop_last=False,
    )

    config = LSTMConfig(
        input_size=x_train.shape[-1],
        hidden_size=hidden_size,
        num_layers=num_layers,
        dropout=dropout,
        num_classes=len(RISK_CLASSES),
    )
    model = AltitudeRiskLSTM(config).to(device)
    weights = torch.tensor(
        class_weights(bundle.y_train, len(RISK_CLASSES)), dtype=torch.float32
    ).to(device)
    criterion = nn.CrossEntropyLoss(weight=weights)
    optimiser = torch.optim.AdamW(model.parameters(), lr=learning_rate, weight_decay=1e-4)
    scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
        optimiser, mode="min", factor=0.5, patience=2
    )

    xv = torch.from_numpy(x_val).to(device)
    yv = torch.from_numpy(bundle.y_val).to(device)

    history: dict[str, list[float]] = {
        "epoch": [],
        "train_loss": [],
        "val_loss": [],
        "train_accuracy": [],
        "val_accuracy": [],
        "learning_rate": [],
    }
    best_val = float("inf")
    best_state: dict[str, Any] | None = None
    best_epoch = 0
    stale = 0
    started = time.perf_counter()

    for epoch in range(1, epochs + 1):
        model.train()
        total_loss = 0.0
        correct = 0
        seen = 0
        for xb, yb in train_dl:
            xb, yb = xb.to(device), yb.to(device)
            optimiser.zero_grad()
            logits = model(xb)
            loss = criterion(logits, yb)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            optimiser.step()
            total_loss += float(loss.item()) * xb.size(0)
            correct += int((logits.argmax(-1) == yb).sum().item())
            seen += xb.size(0)

        model.eval()
        with torch.no_grad():
            val_logits = model(xv)
            val_loss = float(criterion(val_logits, yv).item())
            val_acc = float((val_logits.argmax(-1) == yv).float().mean().item())

        train_loss = total_loss / max(1, seen)
        train_acc = correct / max(1, seen)
        scheduler.step(val_loss)

        history["epoch"].append(epoch)
        history["train_loss"].append(round(train_loss, 5))
        history["val_loss"].append(round(val_loss, 5))
        history["train_accuracy"].append(round(train_acc, 5))
        history["val_accuracy"].append(round(val_acc, 5))
        history["learning_rate"].append(optimiser.param_groups[0]["lr"])

        marker = ""
        if val_loss < best_val - 1e-5:
            best_val, best_epoch, stale = val_loss, epoch, 0
            best_state = {k: v.detach().cpu().clone() for k, v in model.state_dict().items()}
            marker = "  <- best"
        else:
            stale += 1
        print(
            f"  epoch {epoch:3d}/{epochs}  train_loss={train_loss:.4f} "
            f"train_acc={train_acc:.4f}  val_loss={val_loss:.4f} "
            f"val_acc={val_acc:.4f}{marker}",
            flush=True,
        )
        if stale >= patience:
            print(f"  early stopping: no val improvement for {patience} epochs")
            break

    train_seconds = time.perf_counter() - started
    if best_state is not None:
        model.load_state_dict(best_state)

    # --- held-out test evaluation (the only source of reported metrics) ---
    model.eval()
    with torch.no_grad():
        test_logits = model(torch.from_numpy(x_test).to(device))
        test_proba = torch.softmax(test_logits, dim=-1).cpu().numpy()
        val_proba = torch.softmax(model(xv), dim=-1).cpu().numpy()
    test_metrics = classification_metrics(bundle.y_test, test_proba.argmax(axis=1), test_proba)
    val_metrics = classification_metrics(bundle.y_val, val_proba.argmax(axis=1), val_proba)

    info = {
        "architecture": "LSTM(2x96) + attention pooling + MLP head",
        "config": config.as_dict(),
        "hyperparameters": {
            "epochs_requested": epochs,
            "epochs_run": len(history["epoch"]),
            "best_epoch": best_epoch,
            "batch_size": batch_size,
            "learning_rate": learning_rate,
            "optimiser": "AdamW",
            "weight_decay": 1e-4,
            "loss": "CrossEntropyLoss (inverse-frequency class weights)",
            "scheduler": "ReduceLROnPlateau(factor=0.5, patience=2)",
            "grad_clip_norm": 1.0,
            "early_stopping_patience": patience,
            "seed": seed,
        },
        "n_parameters": int(sum(p.numel() for p in model.parameters())),
        "train_seconds": round(train_seconds, 2),
        "metrics": {"validation": val_metrics, "test": test_metrics},
    }
    return model, info, history


def train_gb(bundle: Any, scaler: StandardScaler, seed: int) -> tuple[Any, dict[str, Any]]:
    from ml.baseline import (
        flatten_windows,
        permutation_importance_gb,
        train_gradient_boosting,
    )

    x_train = scaler.transform(bundle.x_train).astype(np.float32)
    x_val = scaler.transform(bundle.x_val).astype(np.float32)
    x_test = scaler.transform(bundle.x_test).astype(np.float32)

    started = time.perf_counter()
    model, info = train_gradient_boosting(x_train, bundle.y_train, x_val, bundle.y_val, seed=seed)
    train_seconds = time.perf_counter() - started

    test_proba = model.predict_proba(flatten_windows(x_test))
    val_proba = model.predict_proba(flatten_windows(x_val))
    info["train_seconds"] = round(train_seconds, 2)
    info["metrics"] = {
        "validation": classification_metrics(bundle.y_val, val_proba.argmax(axis=1), val_proba),
        "test": classification_metrics(bundle.y_test, test_proba.argmax(axis=1), test_proba),
    }
    info["permutation_importance"] = permutation_importance_gb(
        model, x_test, bundle.y_test, seed=seed
    )
    return model, info


def evaluate_rule_baseline(bundle: Any) -> dict[str, Any]:
    """Evaluate the transparent rule baseline on the same held-out split.

    The rule baseline has no trainable parameters: it re-applies the risk
    engine to the *last* timestep of each window and predicts that the future
    category will equal the present one (persistence forecast). This is the
    honest "no machine learning" reference point, and it is exactly what the
    LSTM has to beat to justify its existence.
    """
    from app.core.defaults import DEFAULT_RISK_CATEGORIES
    from app.services.risk_engine import RiskEngine
    from ml.features import BASE_FEATURES

    if bundle.x_test.size == 0:
        return {"n_samples": 0, "note": "empty split"}

    engine = RiskEngine()
    # Reconstruct snapshots from the unscaled windows.
    from datetime import timedelta

    from app.services.risk_engine import VitalSnapshot

    idx = {name: i for i, name in enumerate(BASE_FEATURES)}
    now = datetime(2026, 1, 1, tzinfo=timezone.utc)
    preds = np.zeros(bundle.x_test.shape[0], dtype=np.int64)
    step = max(1, bundle.x_test.shape[0] // 4000)  # subsample: engine is exact
    sampled = list(range(0, bundle.x_test.shape[0], step))
    for _out_i, i in enumerate(sampled):
        window = bundle.x_test[i]
        snaps = [
            VitalSnapshot(
                recorded_at=now + timedelta(minutes=t),
                heart_rate=float(window[t, idx["heart_rate"]]),
                spo2=float(window[t, idx["spo2"]]),
                body_temp_c=float(window[t, idx["body_temp_c"]]),
                respiratory_rate=float(window[t, idx["respiratory_rate"]]),
                bp_systolic=float(window[t, idx["bp_systolic"]]),
                bp_diastolic=float(window[t, idx["bp_diastolic"]]),
                altitude_m=float(window[t, idx["altitude_m"]]),
                fatigue_score=float(window[t, idx["fatigue_score"]]),
                activity_level="MODERATE",
                env_temp_c=float(window[t, idx["env_temp_c"]]),
                wind_kph=float(window[t, idx["wind_kph"]]),
            )
            for t in range(window.shape[0])
        ]
        result = engine.evaluate(snaps[-1], snaps)
        preds[i] = RISK_CLASSES.index(result.category.value)

    y_true = bundle.y_test[sampled]
    y_pred = preds[sampled]
    metrics = classification_metrics(y_true, y_pred)
    metrics["note"] = (
        "Persistence forecast: the rule engine's present category is used as "
        "the prediction for t+horizon. No trainable parameters."
    )
    metrics["subsample_step"] = step
    metrics["categories"] = DEFAULT_RISK_CATEGORIES
    return metrics


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m ml.train",
        description="Train A4S+ altitude health-risk forecasting models on "
        "synthetic simulated data.",
    )
    parser.add_argument(
        "--model",
        choices=["lstm", "gb", "all"],
        default="all",
        help="Which model(s) to train (default: all)",
    )
    parser.add_argument("--subjects", type=int, default=480)
    parser.add_argument("--steps", type=int, default=190)
    parser.add_argument("--sequence-length", type=int, default=24)
    parser.add_argument(
        "--horizon",
        type=int,
        default=30,
        help="Prediction horizon in simulated minutes (default: 30)",
    )
    parser.add_argument("--epochs", type=int, default=30)
    parser.add_argument("--batch-size", type=int, default=256)
    parser.add_argument("--learning-rate", type=float, default=2e-3)
    parser.add_argument("--hidden-size", type=int, default=96)
    parser.add_argument("--num-layers", type=int, default=2)
    parser.add_argument("--dropout", type=float, default=0.25)
    parser.add_argument("--patience", type=int, default=6)
    parser.add_argument("--seed", type=int, default=20260909)
    parser.add_argument("--device", default="cpu", choices=["cpu", "cuda"])
    parser.add_argument(
        "--quick",
        action="store_true",
        help="Small, fast run for smoke-testing the pipeline",
    )
    parser.add_argument(
        "--no-save", action="store_true", help="Do not write artifacts to the registry"
    )
    args = parser.parse_args(argv)

    if args.quick:
        args.subjects, args.steps, args.epochs = 60, 150, 4

    print("=" * 72)
    print("A4S+ model training")
    print(DISCLAIMER)
    print("=" * 72)

    set_seed(args.seed)

    print(
        f"\n[1/5] Building synthetic dataset "
        f"(subjects={args.subjects}, steps={args.steps}, "
        f"seq_len={args.sequence_length}, horizon={args.horizon})"
    )
    t0 = time.perf_counter()
    bundle = build_dataset(
        n_subjects=args.subjects,
        steps=args.steps,
        sequence_length=args.sequence_length,
        horizon=args.horizon,
        seed=args.seed,
    )
    print(bundle.describe())
    print(f"  built in {time.perf_counter() - t0:.1f}s")
    if bundle.x_train.size == 0 or bundle.x_test.size == 0:
        print("ERROR: dataset is empty — increase --steps or --subjects.", file=sys.stderr)
        return 1

    print("\n[2/5] Fitting feature scaler on the training split only")
    scaler = StandardScaler().fit(bundle.x_train)
    print(f"  {len(FEATURE_NAMES)} channels standardised")

    print("\n[3/5] Evaluating the transparent rule baseline (reference point)")
    rule_metrics = evaluate_rule_baseline(bundle)
    print(
        f"  rule baseline: accuracy={rule_metrics.get('accuracy')} "
        f"macro_f1={rule_metrics.get('macro_f1')} "
        f"elevated_recall="
        f"{rule_metrics.get('elevated_risk_binary', {}).get('recall')}"
    )

    dataset_meta = dict(bundle.meta)
    results: dict[str, Any] = {"rule_baseline": rule_metrics}
    saved: list[str] = []

    if args.model in ("lstm", "all"):
        print("\n[4/5] Training the LSTM")
        model, info, history = train_lstm(
            bundle,
            scaler,
            epochs=args.epochs,
            batch_size=args.batch_size,
            learning_rate=args.learning_rate,
            hidden_size=args.hidden_size,
            num_layers=args.num_layers,
            dropout=args.dropout,
            patience=args.patience,
            seed=args.seed,
            device=args.device,
        )
        test = info["metrics"]["test"]
        print(
            f"\n  LSTM held-out test: accuracy={test['accuracy']} "
            f"macro_f1={test['macro_f1']} "
            f"elevated_f1={test['elevated_risk_binary']['f1']} "
            f"roc_auc={test['elevated_risk_binary'].get('roc_auc')}"
        )
        print(format_confusion(test["confusion_matrix"]))
        results["lstm"] = test
        if not args.no_save:
            version = new_version()
            artifact = save_artifact(
                "lstm",
                version,
                {
                    "model_type": "pytorch_lstm",
                    "framework": f"torch {__import__('torch').__version__}",
                    "feature_names": list(FEATURE_NAMES),
                    "classes": list(RISK_CLASSES),
                    "sequence_length": args.sequence_length,
                    "horizon_minutes": dataset_meta["horizon_minutes"],
                    "scaler": scaler.to_dict(),
                    "data_provenance": "SYNTHETIC_SIMULATION",
                    "disclaimer": DISCLAIMER,
                    "dataset": dataset_meta,
                    "explanation_method": "OCCLUSION_SENSITIVITY",
                    **info,
                },
                state_dict=model.state_dict(),
                history=history,
            )
            saved.append(f"lstm/{version}")
            print(f"  artifact saved: {artifact.directory}")

    if args.model in ("gb", "all"):
        print("\n[5/5] Training the gradient-boosting comparison model")
        gb_model, gb_info = train_gb(bundle, scaler, args.seed)
        test = gb_info["metrics"]["test"]
        print(
            f"  GB held-out test: accuracy={test['accuracy']} "
            f"macro_f1={test['macro_f1']} "
            f"elevated_f1={test['elevated_risk_binary']['f1']} "
            f"roc_auc={test['elevated_risk_binary'].get('roc_auc')}"
        )
        results["gradient_boosting"] = test
        if not args.no_save:
            version = new_version()
            artifact = save_artifact(
                "gradient_boosting",
                version,
                {
                    "model_type": "sklearn_hist_gradient_boosting",
                    "feature_names": list(FEATURE_NAMES),
                    "classes": list(RISK_CLASSES),
                    "sequence_length": args.sequence_length,
                    "horizon_minutes": dataset_meta["horizon_minutes"],
                    "scaler": scaler.to_dict(),
                    "data_provenance": "SYNTHETIC_SIMULATION",
                    "disclaimer": DISCLAIMER,
                    "dataset": dataset_meta,
                    "explanation_method": "IMPURITY_IMPORTANCE",
                    **gb_info,
                },
                estimator=gb_model,
            )
            saved.append(f"gradient_boosting/{version}")
            print(f"  artifact saved: {artifact.directory}")

    print("\n" + "=" * 72)
    print("MODEL COMPARISON (held-out synthetic test split)")
    print("=" * 72)
    header = f"{'model':22s}{'accuracy':>10s}{'macro F1':>10s}{'elev F1':>10s}{'ROC AUC':>10s}"
    print(header)
    for name in ("rule_baseline", "lstm", "gradient_boosting"):
        m = results.get(name)
        if not m or not m.get("n_samples"):
            continue
        elev = m.get("elevated_risk_binary", {})
        auc = elev.get("roc_auc")
        print(
            f"{name:22s}{m['accuracy']:>10.4f}{m['macro_f1']:>10.4f}"
            f"{elev.get('f1', 0.0):>10.4f}"
            f"{(f'{auc:.4f}' if isinstance(auc, float) else 'n/a'):>10s}"
        )
    print("\nAll metrics measured on synthetic, subject-disjoint held-out data.")
    if saved:
        print("Artifacts written: " + ", ".join(saved))
        summary_path = __import__("ml.registry", fromlist=["artifact_root"]).artifact_root()
        (summary_path / "last_comparison.json").write_text(
            json.dumps(
                {
                    "generated_at": datetime.now(timezone.utc).isoformat(),
                    "disclaimer": DISCLAIMER,
                    "dataset": dataset_meta,
                    "results": results,
                    "artifacts": saved,
                },
                indent=2,
                default=str,
            )
        )
        print(f"Comparison written: {summary_path / 'last_comparison.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
