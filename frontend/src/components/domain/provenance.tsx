import { FlaskConical, Hand, Radio } from 'lucide-react';

import { Badge } from '@/components/ui/badge';
import { Tooltip, TooltipContent, TooltipTrigger } from '@/components/ui/tooltip';

/**
 * Data-provenance chip.
 *
 * Every place the console shows telemetry it also shows where that telemetry
 * came from. `SIMULATION` is the only source this prototype can actually
 * produce automatically; `MANUAL` means a human typed it in.
 */
export function ProvenanceChip({ source }: { source: string | null | undefined }) {
  const normalised = (source ?? 'SIMULATION').toUpperCase();

  if (normalised === 'MANUAL') {
    return (
      <Tooltip>
        <TooltipTrigger asChild>
          <Badge variant="secondary">
            <Hand className="size-3" />
            Manual entry
          </Badge>
        </TooltipTrigger>
        <TooltipContent>
          Recorded by hand through the console. Not a sensor reading.
        </TooltipContent>
      </Tooltip>
    );
  }

  if (normalised === 'DEVICE' || normalised === 'WEARABLE') {
    return (
      <Tooltip>
        <TooltipTrigger asChild>
          <Badge variant="outline">
            <Radio className="size-3" />
            {normalised}
          </Badge>
        </TooltipTrigger>
        <TooltipContent>
          Declared source. No hardware integration is implemented in this prototype.
        </TooltipContent>
      </Tooltip>
    );
  }

  return (
    <Tooltip>
      <TooltipTrigger asChild>
        <Badge variant="default">
          <FlaskConical className="size-3" />
          Simulated
        </Badge>
      </TooltipTrigger>
      <TooltipContent>
        Generated by the built-in simulation engine. Not real sensor data.
      </TooltipContent>
    </Tooltip>
  );
}
